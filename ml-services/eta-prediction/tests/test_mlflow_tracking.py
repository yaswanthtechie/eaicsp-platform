import numpy as np
import mlflow
import mlflow.sklearn

from src.evaluate import evaluate_model
from src.mlflow_tracking import (
    log_calibration_metadata,
    log_dataset_metadata,
    log_metrics,
    log_model,
    log_parameters,
)
from src.pipeline import create_pipeline


def test_mlflow_tracking_lifecycle(
    tmp_path,
    sample_model_data,
):
    """
    Test the complete MLflow tracking lifecycle.

    Verifies:
    - model parameters are logged
    - evaluation metrics are logged
    - dataset/split metadata is logged
    - prediction interval calibration metadata is logged
    - trained model is logged
    - MLflow returns valid model information
    - logged model can be loaded
    - loaded model can make predictions

    Uses a temporary SQLite MLflow backend so the test
    is independent of the developer's local MLflow database.
    """

    # ---------------------------------------------------------
    # 1. Configure isolated SQLite MLflow tracking
    # ---------------------------------------------------------
    database_path = (
        tmp_path / "mlflow_test.db"
    )

    tracking_uri = (
        f"sqlite:///{database_path}"
    )

    mlflow.set_tracking_uri(
        tracking_uri
    )

    mlflow.set_experiment(
        "ETA Prediction Test"
    )

    # ---------------------------------------------------------
    # 2. Get reusable model data from conftest
    # ---------------------------------------------------------
    X_train = sample_model_data[
        "X_train"
    ]

    y_train = sample_model_data[
        "y_train"
    ]

    X_test = sample_model_data[
        "X_test"
    ]

    train = sample_model_data[
        "train"
    ]

    test = sample_model_data[
        "test"
    ]

    features = sample_model_data[
        "features"
    ]

    split_timestamp = sample_model_data[
        "split_timestamp"
    ]

    # ---------------------------------------------------------
    # 3. Create and train pipeline
    # ---------------------------------------------------------
    pipeline = create_pipeline()

    pipeline.fit(
        X_train,
        y_train,
    )

    assert pipeline is not None

    assert hasattr(
        pipeline,
        "predict",
    )

    # ---------------------------------------------------------
    # 4. Calibration metadata
    #
    # This represents the metadata generated by the
    # training/calibration process.
    # ---------------------------------------------------------
    calibration = {
        "method": "empirical_residual",
        "coverage": 0.90,
        "calibration_fraction": 0.20,
        "lower_quantile": 0.05,
        "upper_quantile": 0.95,
        "residual_lower": -2.0,
        "residual_upper": 2.5,
        "calibration_rows": 2,
    }

    # ---------------------------------------------------------
    # 5. Start MLflow run
    # ---------------------------------------------------------
    with mlflow.start_run():

        run = mlflow.active_run()

        assert run is not None

        run_id = run.info.run_id

        # -----------------------------------------------------
        # 6. Log model parameters
        # -----------------------------------------------------
        log_parameters(pipeline)

        # -----------------------------------------------------
        # 7. Verify parameters
        # -----------------------------------------------------
        run_data = mlflow.get_run(
            run_id
        ).data

        assert (
            run_data.params["model"]
            == "XGBRegressor"
        )

        assert (
            run_data.params["objective"]
            == "reg:squarederror"
        )

        assert (
            run_data.params["n_estimators"]
            == "500"
        )

        assert (
            run_data.params["learning_rate"]
            == "0.05"
        )

        assert (
            run_data.params["max_depth"]
            == "6"
        )

        assert (
            run_data.params["test_size"]
            == "0.2"
        )

        # -----------------------------------------------------
        # 8. Evaluate trained model
        # -----------------------------------------------------
        results = evaluate_model(
            pipeline,
            train,
            test,
        )

        # -----------------------------------------------------
        # 9. Verify evaluation results
        # -----------------------------------------------------
        expected_metrics = {
            "mae",
            "rmse",
            "baseline_mae",
            "baseline_rmse",
            "mae_improvement",
            "rmse_improvement",
        }

        assert expected_metrics.issubset(
            results.keys()
        )

        for metric_name in expected_metrics:
            assert np.isfinite(
                results[metric_name]
            )

        # -----------------------------------------------------
        # 10. Log evaluation metrics
        # -----------------------------------------------------
        log_metrics(
            results
        )

        # -----------------------------------------------------
        # 11. Verify metrics were logged
        # -----------------------------------------------------
        run_data = mlflow.get_run(
            run_id
        ).data

        assert expected_metrics.issubset(
            run_data.metrics.keys()
        )

        for metric_name in expected_metrics:
            assert np.isfinite(
                run_data.metrics[metric_name]
            )

        # -----------------------------------------------------
        # 12. Log dataset/split metadata
        # -----------------------------------------------------
        log_dataset_metadata(
            features=features,
            train=train,
            test=test,
            split_timestamp=split_timestamp,
        )

        # -----------------------------------------------------
        # 13. Verify dataset metadata
        # -----------------------------------------------------
        run_data = mlflow.get_run(
            run_id
        ).data

        assert (
            run_data.params["total_rows"]
            == str(len(features))
        )

        assert (
            run_data.params["train_rows"]
            == str(len(train))
        )

        assert (
            run_data.params["test_rows"]
            == str(len(test))
        )

        assert (
            "training_start"
            in run_data.params
        )

        assert (
            "training_end"
            in run_data.params
        )

        assert (
            "test_start"
            in run_data.params
        )

        assert (
            "test_end"
            in run_data.params
        )

        assert (
            "split_timestamp"
            in run_data.params
        )

        # -----------------------------------------------------
        # 14. Log prediction interval calibration
        # -----------------------------------------------------
        log_calibration_metadata(
            calibration
        )

        # -----------------------------------------------------
        # 15. Verify calibration parameters
        #
        # These names MUST match src.mlflow_tracking.
        # -----------------------------------------------------
        run_data = mlflow.get_run(
            run_id
        ).data

        assert (
            run_data.params[
                "prediction_interval_method"
            ]
            == "empirical_residual"
        )

        assert (
            run_data.params[
                "prediction_interval_coverage"
            ]
            == "0.9"
        )

        assert (
            run_data.params[
                "calibration_fraction"
            ]
            == "0.2"
        )

        assert (
            run_data.params[
                "calibration_rows"
            ]
            == "2"
        )

        assert (
            run_data.params[
                "lower_quantile"
            ]
            == "0.05"
        )

        assert (
            run_data.params[
                "upper_quantile"
            ]
            == "0.95"
        )

        # -----------------------------------------------------
        # 16. Verify calibration residual metrics
        # -----------------------------------------------------
        assert (
            "residual_lower"
            in run_data.metrics
        )

        assert (
            "residual_upper"
            in run_data.metrics
        )

        assert np.isfinite(
            run_data.metrics[
                "residual_lower"
            ]
        )

        assert np.isfinite(
            run_data.metrics[
                "residual_upper"
            ]
        )

        assert (
            run_data.metrics[
                "residual_lower"
            ]
            == -2.0
        )

        assert (
            run_data.metrics[
                "residual_upper"
            ]
            == 2.5
        )

        # -----------------------------------------------------
        # 17. Log trained model
        # -----------------------------------------------------
        model_info = log_model(
            pipeline
        )

        # -----------------------------------------------------
        # 18. Verify MLflow returned model information
        # -----------------------------------------------------
        assert model_info is not None

        assert model_info.model_id

        assert model_info.model_uri

        assert model_info.run_id == run_id

        # -----------------------------------------------------
        # 19. MLflow 3.x logged-model URI
        # -----------------------------------------------------
        assert model_info.model_uri.startswith(
            "models:/"
        )

        # -----------------------------------------------------
        # 20. Verify model ID is represented in URI
        # -----------------------------------------------------
        assert (
            model_info.model_id
            in model_info.model_uri
        )

        # -----------------------------------------------------
        # 21. Load logged model through MLflow
        # -----------------------------------------------------
        loaded_model = (
            mlflow.sklearn.load_model(
                model_info.model_uri
            )
        )

        assert loaded_model is not None

        assert hasattr(
            loaded_model,
            "predict",
        )

        # -----------------------------------------------------
        # 22. Verify loaded model can predict
        # -----------------------------------------------------
        predictions = (
            loaded_model.predict(
                X_test
            )
        )

        assert isinstance(
            predictions,
            np.ndarray,
        )

        assert len(
            predictions
        ) == len(X_test)

        assert np.isfinite(
            predictions
        ).all()

        assert np.issubdtype(
            predictions.dtype,
            np.number,
        )