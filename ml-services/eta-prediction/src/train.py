import joblib
import numpy as np

from .paths import MODEL_PATH
from .pipeline import create_pipeline


# ---------------------------------------------------------
# Prediction interval calibration artifact
# ---------------------------------------------------------
CALIBRATION_MODEL_PATH = (
    MODEL_PATH.parent
    / "eta_prediction_interval.joblib"
)


# ---------------------------------------------------------
# Prediction interval configuration
# ---------------------------------------------------------
PREDICTION_INTERVAL_COVERAGE = 0.80


def train_model(X_train, y_train):
    """
    Train and save the ETA pipeline.

    The model is trained on the complete training dataset.

    An empirical prediction interval is then calibrated using
    out-of-sample predictions generated by a time-preserving
    validation split inside the training data.

    The calibration artifact stores symmetric residual bounds:

        residual_lower = -q
        residual_upper = +q

    where q is the configured absolute-residual quantile.

    This allows prediction to construct:

        lower = prediction + residual_lower
        upper = prediction + residual_upper
    """

    # ---------------------------------------------------------
    # 1. Validate minimum training size
    # ---------------------------------------------------------
    if len(X_train) != len(y_train):
        raise ValueError(
            "X_train and y_train must contain "
            "the same number of rows."
        )

    if len(X_train) < 4:
        raise ValueError(
            "At least 4 training rows are required "
            "for prediction interval calibration."
        )

    # ---------------------------------------------------------
    # 2. Create the production pipeline
    # ---------------------------------------------------------
    pipeline = create_pipeline()

    # ---------------------------------------------------------
    # 3. Create an out-of-sample calibration split
    #
    # The latest portion of the training data is held out
    # temporarily for calibration.
    #
    # This preserves the chronological discipline used by
    # the main train/test evaluation.
    # ---------------------------------------------------------
    calibration_size = max(
        2,
        int(
            len(X_train)
            * 0.20
        ),
    )

    calibration_start = (
        len(X_train)
        - calibration_size
    )

    X_fit = X_train.iloc[
        :calibration_start
    ].copy()

    y_fit = y_train.iloc[
        :calibration_start
    ].copy()

    X_calibration = X_train.iloc[
        calibration_start:
    ].copy()

    y_calibration = y_train.iloc[
        calibration_start:
    ].copy()

    # ---------------------------------------------------------
    # 4. Train temporary calibration model
    # ---------------------------------------------------------
    calibration_pipeline = create_pipeline()

    calibration_pipeline.fit(
        X_fit,
        y_fit,
    )

    # ---------------------------------------------------------
    # 5. Generate out-of-sample calibration predictions
    # ---------------------------------------------------------
    calibration_predictions = (
        calibration_pipeline.predict(
            X_calibration
        )
    )

    calibration_predictions = np.asarray(
        calibration_predictions,
        dtype=float,
    )

    y_calibration_array = np.asarray(
        y_calibration,
        dtype=float,
    )

    # ---------------------------------------------------------
    # 6. Calculate absolute residuals
    #
    # residual = actual - prediction
    #
    # Absolute residual:
    #
    #     |actual - prediction|
    #
    # We use the absolute error magnitude so that the
    # resulting interval is centered around the ETA prediction.
    # ---------------------------------------------------------
    absolute_residuals = np.abs(
        y_calibration_array
        - calibration_predictions
    )

    if not np.isfinite(
        absolute_residuals
    ).all():
        raise ValueError(
            "Prediction interval calibration produced "
            "non-finite residuals."
        )

    # ---------------------------------------------------------
    # 7. Calculate empirical interval width
    # ---------------------------------------------------------
    interval_width = float(
        np.quantile(
            absolute_residuals,
            PREDICTION_INTERVAL_COVERAGE,
        )
    )

    if not np.isfinite(
        interval_width
    ):
        raise ValueError(
            "Prediction interval calibration produced "
            "an invalid interval width."
        )

    # ---------------------------------------------------------
    # 8. Store symmetric residual bounds
    # ---------------------------------------------------------
    calibration = {
        "method": (
            "absolute_residual_quantile"
        ),
        "coverage": (
            PREDICTION_INTERVAL_COVERAGE
        ),
        "calibration_fraction": 0.20,
        "calibration_rows": len(
            X_calibration
        ),
        "lower_quantile": (
            1.0
            - PREDICTION_INTERVAL_COVERAGE
        ),
        "upper_quantile": (
            PREDICTION_INTERVAL_COVERAGE
        ),
        "interval_width": interval_width,
        "residual_lower": -interval_width,
        "residual_upper": interval_width,
    }

    # ---------------------------------------------------------
    # 9. Train final production model
    #
    # IMPORTANT:
    # The final production model uses ALL training rows.
    # The calibration model above is discarded after the
    # interval width has been calculated.
    # ---------------------------------------------------------
    pipeline.fit(
        X_train,
        y_train,
    )

    # ---------------------------------------------------------
    # 10. Save production model
    # ---------------------------------------------------------
    joblib.dump(
        pipeline,
        MODEL_PATH,
    )

    # ---------------------------------------------------------
    # 11. Save prediction interval calibration
    # ---------------------------------------------------------
    joblib.dump(
        calibration,
        CALIBRATION_MODEL_PATH,
    )

    # ---------------------------------------------------------
    # 12. Return final production pipeline
    # ---------------------------------------------------------
    return pipeline