import mlflow
import mlflow.sklearn


EXPERIMENT_NAME = "ETA Prediction"
MODEL_NAME = "eta_pipeline"


def setup_mlflow():
    """Configure the MLflow experiment."""

    mlflow.set_experiment(
        EXPERIMENT_NAME
    )


def start_run():
    """Start an MLflow tracking run."""

    return mlflow.start_run()


def log_parameters():
    """Log the fixed ETA model and split parameters."""

    mlflow.log_params(
        {
            "test_size": 0.20,
            "model": "XGBRegressor",
            "objective": "reg:squarederror",
            "n_estimators": 500,
            "learning_rate": 0.05,
            "max_depth": 6,
            "min_child_weight": 5,
            "subsample": 0.8,
            "colsample_bytree": 0.8,
            "reg_alpha": 0.0,
            "reg_lambda": 1.0,
            "random_state": 42,
            "n_jobs": -1,
        }
    )


def log_metrics(results):
    """Log evaluation metrics returned by evaluate_model()."""

    mlflow.log_metrics(
        {
            "mae": results["mae"],
            "rmse": results["rmse"],
            "baseline_mae": results["baseline_mae"],
            "baseline_rmse": results["baseline_rmse"],
            "mae_improvement": results[
                "mae_improvement"
            ],
            "rmse_improvement": results[
                "rmse_improvement"
            ],
        }
    )


def log_dataset_metadata(
    features,
    train,
    test,
    split_timestamp,
):
    """Log dataset and chronological split metadata."""

    mlflow.log_params(
        {
            "total_rows": len(features),
            "train_rows": len(train),
            "test_rows": len(test),
            "training_start": str(
                train[
                    "order_purchase_timestamp"
                ].min()
            ),
            "training_end": str(
                train[
                    "order_purchase_timestamp"
                ].max()
            ),
            "test_start": str(
                test[
                    "order_purchase_timestamp"
                ].min()
            ),
            "test_end": str(
                test[
                    "order_purchase_timestamp"
                ].max()
            ),
            "split_timestamp": str(
                split_timestamp
            ),
        }
    )


def log_calibration_metadata(
    calibration,
):
    """
    Log prediction interval calibration metadata.

    The calibration values are generated by train_model()
    from out-of-sample residuals on the training portion.
    """

    mlflow.log_params(
        {
            "prediction_interval_method": str(
                calibration["method"]
            ),
            "prediction_interval_coverage": str(
                calibration["coverage"]
            ),
            "calibration_fraction": str(
                calibration["calibration_fraction"]
            ),
            "calibration_rows": str(
                calibration["calibration_rows"]
            ),
            "lower_quantile": str(
                calibration["lower_quantile"]
            ),
            "upper_quantile": str(
                calibration["upper_quantile"]
            ),
        }
    )

    mlflow.log_metrics(
        {
            "residual_lower": float(
                calibration["residual_lower"]
            ),
            "residual_upper": float(
                calibration["residual_upper"]
            ),
        }
    )


def log_model(model):
    """
    Log the trained ETA pipeline to MLflow.

    The production joblib artifact created by train_model()
    remains unchanged. MLflow stores its own tracked copy.
    """

    model_info = mlflow.sklearn.log_model(
        sk_model=model,
        name=MODEL_NAME,
        serialization_format=(
            mlflow.sklearn.SERIALIZATION_FORMAT_CLOUDPICKLE
        ),
    )

    return model_info