def test_compliance_internal_check_response_contract_decisions():
    """
    Contract test for Geethika's /internal-check endpoint response shape.
    Proves that all possible decisions (CLEAR, BLOCK, REVIEW) conform to schema.
    """
    clear_resp = ComplianceCheckContractResponse(
        cleared=True,
        decision="CLEAR",
        reason="Supplier cleared all sanctions lists",
    )
    assert clear_resp.cleared is True
    assert clear_resp.decision == "CLEAR"

    block_resp = ComplianceCheckContractResponse(
        cleared=False,
        decision="BLOCK",
        reason="Supplier is on OFAC sanctions list",
    )
    assert block_resp.cleared is False
    assert block_resp.decision == "BLOCK"

    review_resp = ComplianceCheckContractResponse(
        cleared=False,
        decision="REVIEW",
        reason="Fuzzy match found on PEP list",
    )
    assert review_resp.cleared is False
    assert review_resp.decision == "REVIEW"


