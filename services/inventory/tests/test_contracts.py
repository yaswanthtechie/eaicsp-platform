# 1. Rahul's Platform Service Contract: /api/v1/auth/verify
class PlatformVerifyContractResponse(BaseModel):
    valid: bool
    user_id: int
    email: str
    full_name: Optional[str] = None
    role: Optional[str] = None
    supplier_id: Optional[str] = None
    is_active: Optional[bool] = True
    permissions: list[str] = Field(default_factory=list)


# 2. Geethika's Compliance Service Contract: /api/v1/compliance/internal-check
class ComplianceCheckContractRequest(BaseModel):
    supplier_id: str
    supplier_name: str
    country: str


class ComplianceCheckContractResponse(BaseModel):
    cleared: bool
    decision: Literal["CLEAR", "BLOCK", "REVIEW"]
    reason: str


